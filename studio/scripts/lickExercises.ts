/** Guide-tone lines and chord-tone and scale lines through the progressions. */
function progressionExercises(): Chart[] {
  const out: Chart[] = []
  for (const progression of PROGRESSIONS) {
    const add = (category: string, title: string, notes: TimedNote[], tags: string[], level: number) =>
      out.push(makeLickChart({ title: `${capital(progression.name)}: ${title}`, chords: progression.spans, notes,
        info: exercise(category, progression.context, tags, level) }))
    add('Guide tones', 'guide tones, one per chord, from the 3rd', guideToneLine(progression.spans, 1, 'third'), ['guide tones'], 1)
    add('Guide tones', 'guide tones, one per chord, from the 7th', guideToneLine(progression.spans, 1, 'seventh'), ['guide tones'], 1)
    add('Guide tones', 'guide tones, two per chord', guideToneLine(progression.spans, 2, 'third'), ['guide tones'], 1)
    add('Chord-tone lines', 'chord tones in eighth notes', eighthLine(progression.spans, false), ['arpeggio', 'voice leading'], progression.level)
    if (progression.scales) add('Chord-tone lines', 'chord scales in eighth notes', eighthLine(progression.spans, true), ['scale', 'voice leading'], progression.level)
  }
  return out
}

/** Approach notes and enclosures into the chord tones of C major 7, C minor 7 and C7. */
function approachExercises(): Chart[] {
  const chords: [string, number[], number[]][] = [
    ['C^7', [0, 4, 7, 11], SCALES[0].steps],
    ['C-7', [0, 3, 7, 10], SCALES[1].steps],
    ['C7', [0, 4, 7, 10], SCALES[4].steps],
  ]
  const above = (scale: number[], target: number) => target + Math.min(...scale.map((s) => ((s - target) % 12 + 12) % 12).filter((d) => d > 0))
  // Each kind: its cells (approach notes, then the target), their lengths, and where the first cell starts
  const kinds: [string, (scale: number[], t: number) => number[], number[], number, string[]][] = [
    ['chromatic approach from below', (_, t) => [t - 1, t], [0.5, 1.5], 1.5, ['chromatic']],
    ['scale approach from above', (s, t) => [above(s, t), t], [0.5, 1.5], 1.5, ['approach']],
    ['double chromatic approach from below', (_, t) => [t - 2, t - 1, t], [0.5, 0.5, 1], 0, ['chromatic']],
    ['enclosure: scale step above, half step below', (s, t) => [above(s, t), t - 1, t], [0.5, 0.5, 1], 0, ['enclosure']],
    ['enclosure: half step below, scale step above', (s, t) => [t - 1, above(s, t), t], [0.5, 0.5, 1], 0, ['enclosure']],
    ['enclosure: half steps above and below', (_, t) => [t + 1, t - 1, t], [0.5, 0.5, 1], 0, ['enclosure', 'chromatic']],
  ]
  const out: Chart[] = []
  for (const [symbol, tones, scale] of chords) {
    for (const [name, cell, lengths, offset, tags] of kinds) {
      const targets = [...tones, 12].map((t) => 60 + t)
      const pitches = targets.flatMap((t) => cell(scale.map((s) => 60 + s), t))
      // Targets land on the beat: the approach notes fill the beat or half beat before
      const notes = line(offset, pitches, lengths)
      const end = Math.ceil(Math.max(...notes.map((n) => n.start + n.beats)) / 4) * 4
      out.push(makeLickChart({ title: `${symbol}: ${name}`, chords: [[symbol, end]], notes,
        info: exercise('Approach notes and enclosures', symbol, tags, 2) }))
    }
  }
  // Enclosing the third of each chord of a ii-V-I chain and of the blues
  for (const progression of PROGRESSIONS.filter((p) => ['ii-V-I', 'blues'].includes(p.context))) {
    const changes = readChanges(progression.spans)
    const notes: TimedNote[] = []
    let time = 0
    let last = 64
    changes.forEach(({ beats, chord }, i) => {
      const third = closestInRange([tonesOf(chord)[1]], last, 57, 77)
      notes.push({ start: time, beats: i === changes.length - 1 ? beats : beats - 1, pitch: third })
      const next = changes[i + 1]
      if (next) {
        const target = closestInRange([tonesOf(next.chord)[1]], third, 57, 77)
        notes.push({ start: time + beats - 1, beats: 0.5, pitch: target + 1 }, { start: time + beats - 0.5, beats: 0.5, pitch: target - 1 })
      }
      last = third
      time += beats
    })
    out.push(makeLickChart({ title: `${capital(progression.name)}: enclosing every 3rd`, chords: progression.spans, notes,
      info: exercise('Approach notes and enclosures', progression.context, ['enclosure', 'guide tones'], 2) }))
  }
  return out
}

/** Rhythm drills on a C7 vamp, walking the C mixolydian scale (after Kelly and Rasmussen's rhythmic exercises). */
function rhythmExercises(): Chart[] {
  const scale = SCALES[4].steps
  const walk = (count: number) => Array.from({ length: count }, (_, i) => {
    const cycle = i % 14
    return 60 + stepOf(scale, cycle < 8 ? cycle : 14 - cycle)
  })
  const drills: [string, TimedNote[], number][] = []
  // Notes on every off-beat
  drills.push(['eighth notes on every off-beat', walk(16).map((pitch, i) => ({ start: i + 0.5, beats: 0.5, pitch })), 1])
  // Anticipations: off-beats before 1 and 3, held over the beat
  drills.push(['anticipations: the off-beats before 1 and 3', walk(8).map((pitch, i) => ({ start: i * 2 + 1.5, beats: 1, pitch })), 1])
  // On the beat for a bar, off the beat for the next
  drills.push(['on the beat, then off the beat', walk(16).map((pitch, i) => ({ start: i + (Math.floor(i / 4) % 2 ? 0.5 : 0), beats: 0.5, pitch })), 1])
  // Charleston: a dotted quarter on 1, an eighth on the and of 2
  drills.push(['Charleston rhythm', walk(8).map((pitch, i) => ({ start: Math.floor(i / 2) * 4 + (i % 2 ? 1.5 : 0), beats: i % 2 ? 0.5 : 1.5, pitch })), 1])
  // Groups of four and of five eighths with an eighth rest: the groups shift across the beat
  for (const size of [3, 4, 5]) {
    const notes: TimedNote[] = []
    const pitches = walk(64)
    let p = 0
    for (let slot = 0; slot < 32; slot++) if (slot % (size + 1) !== size) notes.push({ start: slot * 0.5, beats: 0.5, pitch: pitches[p++] })
    drills.push([`groups of ${size} eighth notes and an eighth rest`, notes, 2])
  }
  // Quarter-note triplets: three notes over two beats
  drills.push(['quarter-note triplets', walk(12).map((pitch, i) => ({ start: (i * 2) / 3, beats: 2 / 3, pitch })), 2])
  return drills.map(([name, notes, level]) => {
    const end = Math.ceil(Math.max(...notes.map((n) => n.start + n.beats)) / 4) * 4
    return makeLickChart({ title: `Rhythm on C7: ${name}`, chords: [['C7', end]], notes,
      info: exercise('Rhythm', 'C7 vamp', ['rhythm', ...(name.includes('triplet') ? ['triplets'] : [])], level, KELLY_RASMUSSEN) })
  })
}

