// and without the fifth), guide-tone and chord-tone lines through common progressions, scales and
// scale patterns, intervals, approach notes and enclosures, rhythm drills, and a small vocabulary
// of licks written for this project. Everything is in C; the players transpose to any key.
//
// The triad, interval and rhythm drills follow the exercise families of K. B. Kelly and
