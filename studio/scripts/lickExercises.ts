/** A single-chord drill: steps of a scale from middle C in notes of `length`, closing on the nearest C. */
function scaleDrill(title: string, category: string, scale: (typeof SCALES)[number], steps: number[], length: number,
  tags: string[], level: number, credit?: string): Chart {
  const notes = line(0, steps.map((step) => 60 + stepOf(scale.steps, step)), length)
  // The closing C follows the line at once and lasts to the end of its bar
  const end = Math.round(steps.length * length * 1e6) / 1e6
  const close = Math.ceil((end + 1) / 4 - 1e-9) * 4
  notes.push({ start: end, beats: close - end, pitch: nearest(0, notes[notes.length - 1].pitch) })
  return makeLickChart({ title, chords: [[scale.chord, close]], notes,
    info: exercise(category, scale.name, ['scale', ...(scale.tags ?? []), ...tags], level, credit) })
}

